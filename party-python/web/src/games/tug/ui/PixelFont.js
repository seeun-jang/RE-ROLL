/** 글리프 비트맵 → 가로 런(run) 목록 [x, y, 길이] (fillRect 호출 수를 줄이기 위해 미리 계산) */
function buildRuns(rows) {
  const runs = [];
  for (let ry = 0; ry < rows.length; ry++) {
    const row = rows[ry];
    let start = -1;
    for (let rx = 0; rx <= row.length; rx++) {
      const on = rx < row.length && row[rx] === '#';
      if (on && start < 0) start = rx;
      if (!on && start >= 0) {
        runs.push(Object.freeze([start, ry, rx - start]));
        start = -1;
      }
    }
  }
  return Object.freeze(runs);
}

// 불변 런 표 (모듈 로드 시 1회 계산, 이후 절대 바뀌지 않음)
const RUNS = Object.freeze(
  Object.fromEntries(Object.entries(GLYPHS).map(([ch, rows]) => [ch, buildRuns(rows)])),
);

/** 문자 → 글리프 키. 소문자는 대문자로 (단, 'x' 는 곱하기 기호). 없는 글자는 null(빈칸) */
function glyphRuns(ch) {
  if (ch === 'x') return RUNS.x;
  const up = ch.toUpperCase();
  return Object.prototype.hasOwnProperty.call(RUNS, up) ? RUNS[up] : null;
}

/** 텍스트 폭(px) — 고정폭: 글자수×5 + 사이 간격, 전체에 배율 적용 */
export function measureBitmapText(text, scale = 1, spacing = 1) {
  const n = Array.from(String(text ?? '')).length;
  if (n === 0) return 0;
  const s = Math.max(1, Math.round(scale));
  const sp = Math.max(0, Math.round(spacing));
  return (n * GLYPH_W + (n - 1) * sp) * s;
}

/** 한 색으로 글자들을 찍는다 (내부) */
function drawRuns(g, chars, x, y, s, sp, color) {
  g.fillStyle = color;
  const advance = (GLYPH_W + sp) * s;
  let cx = x;
  for (const ch of chars) {
    const runs = glyphRuns(ch);
    if (runs) {
      for (const r of runs) g.fillRect(cx + r[0] * s, y + r[1] * s, r[2] * s, s);
    }
    cx += advance;
  }
}

/**
 * 비트맵 텍스트 그리기. y 는 글자 윗변.
 * @returns 그려진 폭(px)
 */
export function drawBitmapText(g, text, x, y, { color = '#f4f4f4', scale = 1, align = 'left', shadow = null, spacing = 1 } = {}) {
  const chars = Array.from(String(text ?? ''));
  if (chars.length === 0) return 0;
  const s = Math.max(1, Math.round(scale));
  const sp = Math.max(0, Math.round(spacing));
  const w = measureBitmapText(chars.join(''), s, sp);
  // 정렬: 시작 x 를 정수로 맞춘다
  let x0 = Math.round(x);
  if (align === 'center') x0 -= Math.floor(w / 2);
  else if (align === 'right') x0 -= w;
  const y0 = Math.round(y);
  // 그림자는 1*scale px 오른쪽 아래에 먼저 찍는다
  if (shadow) drawRuns(g, chars, x0 + s, y0 + s, s, sp, shadow);
  drawRuns(g, chars, x0, y0, s, sp, color);
  return w;
}
