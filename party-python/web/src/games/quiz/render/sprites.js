/** 여러 조각을 겹친다. parts: [{rows, dy}] — 뒤에 오는 조각이 위에 그려짐 */
function compose(w, h, parts) {
  const grid = Array.from({ length: h }, () => Array(w).fill('.'));
  for (const { rows, dy = 0 } of parts) {
    rows.forEach((row, y) => {
      const ty = y + dy;
      if (ty < 0 || ty >= h) return;
      [...row].forEach((ch, x) => {
        if (ch !== '.' && x < w) grid[ty][x] = ch;
      });
    });
  }
  return grid.map((r) => r.join(''));
}

function character(faceName, arms, headDy = 0, armDy = 0) {
  const head = [...HEAD_TOP, ...face(faceName), ...HEAD_BOTTOM];
  const armParts = arms.map((a) => ({ rows: a, dy: armDy }));
  return compose(16, 32, [
    { rows: [...Array(16).fill(BLANK_ROW), ...BODY] },
    ...armParts,
    { rows: head, dy: headDy },
  ]);
}

