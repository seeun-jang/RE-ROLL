// 팔 조각 (32행 전체 좌표, '.' 은 그리지 않음)
const BLANK_ROW = '................';
function overlay(rowsByIndex) {
  const out = Array(32).fill(BLANK_ROW);
  for (const [i, row] of Object.entries(rowsByIndex)) out[Number(i)] = row;
  return out;
}
